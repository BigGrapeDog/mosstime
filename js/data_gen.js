let counter=0;
const usedNames=new Set(SPECIES.map(s=>s.name));

function hashStr(s){ let h=2166136261; for(let i=0;i<s.length;i++){h^=s.charCodeAt(i);h=Math.imul(h,16777619);} return h>>>0; }

for(const fam of FAMILIES){
  for(let i=0;i<fam.count;i++){
    let name, guard=0;
    do{ name=pick(fam.pre)+pick(fam.suf); guard++; }while(usedNames.has(name)&&guard<60);
    if(usedNames.has(name)) continue;
    usedNames.add(name);
    const id="gen_"+fam.style+"_"+(++counter);
    const need=fam.need().map(r1), tol=fam.tol().map(r1);
    const h=hashStr(id);
    const sci1=fam.sci[h%fam.sci.length], sci2=fam.sci[(h>>>3)%fam.sci.length];
    SPECIES.push({
      id, name, style:fam.style, tier: fam.extremo?3:(rnd()<0.55?1:2),
      need, tol, subs:fam.subs(), hue:Math.round(fam.hue()),
      sci: sci1===sci2?sci1:sci1+sci2,
      poem: fam.poem[(h>>>5)%fam.poem.length],
    });
  }
}
