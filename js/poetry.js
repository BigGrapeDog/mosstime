const PoemSys = {
  bag:[], timer:null, running:true,

  shuffle(){
    this.bag=[...POEMS];
    for(let i=this.bag.length-1;i>0;i--){
      const j=Math.floor(Math.random()*(i+1));
      [this.bag[i],this.bag[j]]=[this.bag[j],this.bag[i]];
    }
  },

  start(){
    this.shuffle();
    setTimeout(()=>this.show(), 4000);
  },

  show(){
    if(!this.running) return;
    if(!this.bag.length) this.shuffle(); // 池尽重洗
    const poem=this.bag.pop();
    const layer=document.getElementById("poem-layer");
    if(!layer) return;
    const el=document.createElement("div");
    el.className="poem-line";
    el.innerHTML=`<span class="poem-text">${poem.t}</span><span class="poem-author">—— ${poem.a}</span>`;
    // 避开中央视野：左带 / 右带 / 上带 / 下带
    const zone=Math.random();
    if(zone<0.35){ el.style.left=(4+Math.random()*14)+"%"; el.style.top=(10+Math.random()*75)+"%"; }
    else if(zone<0.7){ el.style.left=(68+Math.random()*6)+"%"; el.style.top=(10+Math.random()*75)+"%"; }
    else if(zone<0.85){ el.style.left=(25+Math.random()*50)+"%"; el.style.top=(4+Math.random()*6)+"%"; }
    else { el.style.left=(25+Math.random()*50)+"%"; el.style.top=(88+Math.random()*6)+"%"; }
    layer.appendChild(el);
    setTimeout(()=>el.classList.add("on"),50);
    setTimeout(()=>{ el.classList.remove("on"); el.classList.add("off"); }, 16000);
    setTimeout(()=>el.remove(), 21000);
    this.timer=setTimeout(()=>this.show(), 9000+Math.random()*6000);
  },

  toggle(){
    this.running=!this.running;
    if(!this.running){
      clearTimeout(this.timer);
      document.querySelectorAll(".poem-line").forEach(e=>e.remove());
    }else{
      this.show();
    }
    return this.running;
  },
};
